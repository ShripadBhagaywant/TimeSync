export interface TranscriptResponse {
  /** Missing policy fields in old saved workspaces do not establish approval. */
  contentEligibility?: ContentEligibility;
  verificationLevel?: VerificationLevel;
  contentReasonCode?: ContentReasonCode;
  videoId: string;
  title: string;
  channelName: string;
  thumbnailUrl: string;
  content: string;
  transcriptSegments: TranscriptSegment[];
  duration: string;
  cleanedTranscript: string;
  cleaningStage: CleaningStage;

  noteSource?: NoteSource;
  sourceDisclaimer?: string;

  chapters: ChapterDto[];
  /** Optional for workspaces saved before chapter availability was exposed. */
  chapterAvailability?: ChapterAvailability;
  isEditableChapters: boolean;
  cachedResponse: boolean;

  transcriptAvailability?: TranscriptAvailability;
  transcriptLanguage?: string;
  targetLanguage?: string;

  aiRefinementEnabled?: boolean;

  /**
   * Backend-defined provider cooldown.
   *
   * Used for AI availability errors such as Gemini 503/429.
   */
  retryAfterSeconds?: number | null;

  aiStatus?: AiProcessingStatus;
  aiJobId?: string | null;
  aiMessage?: string;

  autoGeneratedCaptions?: boolean;
  selectedCaptionTrackName?: string;
  availableCaptionTracks?: CaptionTrack[];
}

