package com.timesync.notes.dto.response;

import com.timesync.notes.entity.ChapterAvailability;
import com.timesync.notes.entity.ContentEligibility;
import com.timesync.notes.guardrail.*;

import com.timesync.notes.entity.CleaningStage;
import com.timesync.notes.entity.NoteSource;
import com.timesync.notes.entity.TranscriptAvailability;
import com.timesync.notes.entity.AiProcessingStatus;
import java.util.List;

public record TranscriptResponse(
        String videoId,
        String title,
        String channelName,
        String thumbnailUrl,
        String content,
        List<TranscriptSegmentDto> transcriptSegments,
        String duration,
        String cleanedTranscript,
        CleaningStage cleaningStage,
        NoteSource noteSource,
        String sourceDisclaimer,
        List<ChapterDto> chapters,
        boolean isEditableChapters,
        boolean cachedResponse,
        TranscriptAvailability transcriptAvailability,
        String transcriptLanguage,
        String targetLanguage,
        boolean aiRefinementEnabled,
        Integer retryAfterSeconds,
        boolean autoGeneratedCaptions,
        String selectedCaptionTrackName,
        List<CaptionTrackDto> availableCaptionTracks,
        AiProcessingStatus aiStatus,
        String aiJobId,
        String aiMessage,
        ChapterAvailability chapterAvailability,
        ContentEligibility contentEligibility,
        VerificationLevel verificationLevel,
        ContentReasonCode contentReasonCode
) {
    public TranscriptResponse(
        String videoId,
        String title,
        String channelName,
        String thumbnailUrl,
        String content,
        List<TranscriptSegmentDto> transcriptSegments,
        String duration,
        String cleanedTranscript,
        CleaningStage cleaningStage,
        NoteSource noteSource,
        String sourceDisclaimer,
        List<ChapterDto> chapters,
        boolean isEditableChapters,
        boolean cachedResponse,
        TranscriptAvailability transcriptAvailability,
        String transcriptLanguage,
        String targetLanguage,
        boolean aiRefinementEnabled,
        Integer retryAfterSeconds,
        boolean autoGeneratedCaptions,
        String selectedCaptionTrackName,
        List<CaptionTrackDto> availableCaptionTracks,
        AiProcessingStatus aiStatus,
        String aiJobId,
        String aiMessage,
        ChapterAvailability chapterAvailability
    ) {
        this(videoId, title, channelName, thumbnailUrl, content, transcriptSegments, duration, cleanedTranscript, cleaningStage, noteSource, sourceDisclaimer, chapters, isEditableChapters, cachedResponse, transcriptAvailability, transcriptLanguage, targetLanguage, aiRefinementEnabled, retryAfterSeconds, autoGeneratedCaptions, selectedCaptionTrackName, availableCaptionTracks, aiStatus, aiJobId, aiMessage, chapterAvailability, ContentEligibility.UNKNOWN, VerificationLevel.UNVERIFIED,
                noteSource == NoteSource.METADATA ? ContentReasonCode.TRANSCRIPT_UNAVAILABLE : ContentReasonCode.METADATA_INCONCLUSIVE);
    }

    public ContentPolicyDecision contentPolicy() {
        return new ContentPolicyDecision(contentEligibility, verificationLevel, contentReasonCode, "");
    }

    public TranscriptResponse withContentPolicy(ContentPolicyDecision decision) {
        java.util.Objects.requireNonNull(decision, "A content policy decision is required");
        return new TranscriptResponse(videoId, title, channelName, thumbnailUrl, content, transcriptSegments, duration, cleanedTranscript, cleaningStage, noteSource, sourceDisclaimer, chapters, isEditableChapters, cachedResponse, transcriptAvailability, transcriptLanguage, targetLanguage, aiRefinementEnabled, retryAfterSeconds, autoGeneratedCaptions, selectedCaptionTrackName, availableCaptionTracks, aiStatus, aiJobId, aiMessage, chapterAvailability, decision.eligibility(), decision.verificationLevel(), decision.reasonCode());
    }

    public TranscriptResponse(
        String videoId,
        String title,
        String channelName,
        String thumbnailUrl,
        String content,
        List<TranscriptSegmentDto> transcriptSegments,
        String duration,
        String cleanedTranscript,
        CleaningStage cleaningStage,
        NoteSource noteSource,
        String sourceDisclaimer,
        List<ChapterDto> chapters,
        boolean isEditableChapters,
        boolean cachedResponse,
        TranscriptAvailability transcriptAvailability,
        String transcriptLanguage,
        String targetLanguage,
        boolean aiRefinementEnabled,
        Integer retryAfterSeconds,
        boolean autoGeneratedCaptions,
        String selectedCaptionTrackName,
        List<CaptionTrackDto> availableCaptionTracks,
        AiProcessingStatus aiStatus,
        String aiJobId,
        String aiMessage
    ) {
        this(videoId, title, channelName, thumbnailUrl,
                content, transcriptSegments, duration, cleanedTranscript,
                cleaningStage, noteSource, sourceDisclaimer, chapters,
                isEditableChapters, cachedResponse, transcriptAvailability, transcriptLanguage,
                targetLanguage, aiRefinementEnabled, retryAfterSeconds, autoGeneratedCaptions,
                selectedCaptionTrackName, availableCaptionTracks, aiStatus, aiJobId,
                aiMessage, chapters == null || chapters.isEmpty() ? ChapterAvailability.NONE : ChapterAvailability.AVAILABLE);
    }

    public TranscriptResponse withChapterAvailability(ChapterAvailability availability) {
        return new TranscriptResponse(videoId, title, channelName, thumbnailUrl,
                content, transcriptSegments, duration, cleanedTranscript,
                cleaningStage, noteSource, sourceDisclaimer, chapters,
                isEditableChapters, cachedResponse, transcriptAvailability, transcriptLanguage,
                targetLanguage, aiRefinementEnabled, retryAfterSeconds, autoGeneratedCaptions,
                selectedCaptionTrackName, availableCaptionTracks, aiStatus, aiJobId,
                aiMessage, availability, contentEligibility, verificationLevel, contentReasonCode);
    }

    public TranscriptResponse(
            String videoId,
            String title,
            String channelName,
            String thumbnailUrl,
            String content,
            List<TranscriptSegmentDto> transcriptSegments,
            String duration,
            String cleanedTranscript,
            CleaningStage cleaningStage,
            NoteSource noteSource,
            String sourceDisclaimer,
            List<ChapterDto> chapters,
            boolean isEditableChapters,
            boolean cachedResponse,
            TranscriptAvailability transcriptAvailability,
            String transcriptLanguage,
            String targetLanguage,
            boolean aiRefinementEnabled,
            Integer retryAfterSeconds) {
        this(
                videoId, title, channelName, thumbnailUrl, content, transcriptSegments,
                duration, cleanedTranscript, cleaningStage, noteSource, sourceDisclaimer,
                chapters, isEditableChapters, cachedResponse, transcriptAvailability,
                transcriptLanguage, targetLanguage, aiRefinementEnabled, retryAfterSeconds,
                false, "", List.of(),
                aiRefinementEnabled ? AiProcessingStatus.QUEUED : AiProcessingStatus.NOT_REQUESTED,
                null, ""
        );
    }
}
