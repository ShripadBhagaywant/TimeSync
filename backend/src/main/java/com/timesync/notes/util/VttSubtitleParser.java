package com.timesync.notes.util;

import com.timesync.notes.dto.response.TranscriptSegmentDto;
import com.timesync.notes.model.ExtractedTranscript;
import org.springframework.web.util.HtmlUtils;

import java.io.BufferedReader;
import java.io.StringReader;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public final class VttSubtitleParser {

    private static final Pattern TIMING_PATTERN = Pattern.compile(
            "^(?:(\\d{1,2}):)?(\\d{2}):(\\d{2})[.,](\\d{3})\\s+-->\\s+" +
                    "(?:(\\d{1,2}):)?(\\d{2}):(\\d{2})[.,](\\d{3}).*$"
    );

    private VttSubtitleParser() {}

    public static ExtractedTranscript parse(
            String vttContent,
            String languageCode,
            boolean autoGenerated) {
        if (vttContent == null || vttContent.isBlank()) {
            return new ExtractedTranscript("", List.of(), languageCode, autoGenerated);
        }

        StringBuilder textBuilder = new StringBuilder();
        List<TranscriptSegmentDto> segments = new ArrayList<>();
        String lastCueText = "";

        try (BufferedReader reader = new BufferedReader(new StringReader(vttContent))) {
            String line;
            while ((line = reader.readLine()) != null) {
                line = line.trim();
                Matcher timingMatcher = TIMING_PATTERN.matcher(line);
                if (!timingMatcher.matches()) {
                    if (line.contains("-->")) throw new IllegalArgumentException("Invalid VTT timing");
                    continue;
                }

                double startSeconds = parseTimestamp(timingMatcher, 1);
                double endSeconds = parseTimestamp(timingMatcher, 5);
                if (endSeconds < startSeconds) throw new IllegalArgumentException("Invalid VTT interval");
                StringBuilder cueBuilder = new StringBuilder();

                while ((line = reader.readLine()) != null && !line.isBlank()) {
                    String sanitizedLine = sanitizeCueLine(line);
                    if (!sanitizedLine.isBlank()) {
                        if (cueBuilder.length() > 0) {
                            cueBuilder.append(' ');
                        }
                        cueBuilder.append(sanitizedLine);
                    }
                }

                String cueText = cueBuilder.toString().replaceAll("\\s+", " ").trim();
                if (cueText.isBlank()) {
                    continue;
                }

                String uniqueText = deduplicateRollingCue(lastCueText, cueText);
                lastCueText = cueText;
                if (uniqueText.isBlank()) {
                    continue;
                }

                if (textBuilder.length() > 0) {
                    textBuilder.append(' ');
                }
                textBuilder.append(uniqueText);
                segments.add(new TranscriptSegmentDto(
                        startSeconds,
                        Math.max(0, endSeconds - startSeconds),
                        uniqueText
                ));
            }
        } catch (Exception e) {
            throw new IllegalArgumentException("Malformed VTT caption payload");
        }

        return new ExtractedTranscript(
                textBuilder.toString(),
                segments,
                languageCode,
                autoGenerated
        );
    }

    private static String sanitizeCueLine(String line) {
        return HtmlUtils.htmlUnescape(line.replaceAll("<[^>]*>", " "))
                .replace("&nbsp;", " ")
                .trim();
    }

    private static String deduplicateRollingCue(String previous, String current) {
        if (current.equals(previous) || previous.startsWith(current)) {
            return "";
        }
        if (!previous.isBlank() && current.startsWith(previous)) {
            return current.substring(previous.length()).trim();
        }
        return current;
    }

    private static double parseTimestamp(Matcher matcher, int offset) {
        long hours = matcher.group(offset) == null ? 0 : Long.parseLong(matcher.group(offset));
        long minutes = Long.parseLong(matcher.group(offset + 1));
        long seconds = Long.parseLong(matcher.group(offset + 2));
        long millis = Long.parseLong(matcher.group(offset + 3));
        return hours * 3600 + minutes * 60 + seconds + millis / 1000.0;
    }
}
