package com.timesync.notes.integration.youtube;

import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;
import org.xml.sax.InputSource;
import org.xml.sax.helpers.DefaultHandler;

import javax.xml.parsers.DocumentBuilderFactory;
import java.io.StringReader;
import java.util.ArrayList;
import java.util.List;

@lombok.extern.slf4j.Slf4j
public final class YoutubeTimedTextTrackParser {

    private YoutubeTimedTextTrackParser() {
    }

    public static List<Track> parse(String xml) {
        try { return parseValidated(xml); }
        catch (IllegalArgumentException ignored) { return List.of(); }
    }

    public static List<Track> parseValidated(String xml) {
        if (xml == null || xml.isBlank()) {
            return List.of();
        }

        try {
            DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
            factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
            factory.setFeature("http://xml.org/sax/features/external-general-entities", false);
            factory.setFeature("http://xml.org/sax/features/external-parameter-entities", false);
            factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
            factory.setXIncludeAware(false);
            factory.setExpandEntityReferences(false);

            var builder = factory.newDocumentBuilder();
            builder.setErrorHandler(new DefaultHandler());
            Document document = builder.parse(new InputSource(new StringReader(xml)));
            if (!document.getDocumentElement().getTagName().equals("transcript_list"))
                throw new IllegalArgumentException("Unexpected track list format");
            NodeList nodes = document.getElementsByTagName("track");
            List<Track> tracks = new ArrayList<>();
            for (int index = 0; index < nodes.getLength(); index++) {
                Element track = (Element) nodes.item(index);
                String languageCode = track.getAttribute("lang_code").trim();
                if (languageCode.isBlank()) {
                    continue;
                }
                tracks.add(new Track(
                        languageCode,
                        track.getAttribute("name").trim(),
                        "asr".equalsIgnoreCase(track.getAttribute("kind")),
                        track.getAttribute("lang_translated").trim()
                ));
            }
            return List.copyOf(tracks);
        } catch (Exception ignored) {
            log.debug("Timedtext discovery parse result. reason=MALFORMED_CAPTION_PAYLOAD, errorType={}", ignored.getClass().getSimpleName());
            throw new IllegalArgumentException("Malformed caption track list");
        }
    }

    public record Track(
            String languageCode,
            String name,
            boolean autoGenerated,
            String displayName
    ) {
    }
}
