package com.timesync.notes.model;

import com.timesync.notes.dto.response.TranscriptSegmentDto;
import com.timesync.notes.dto.response.CaptionTrackDto;

import java.util.List;

public record ExtractedTranscript(
        String content,
        List<TranscriptSegmentDto> segments,
        String languageCode,
        boolean autoGenerated,
        String captionTrackName,
        List<CaptionTrackDto> availableCaptionTracks
) {
    public ExtractedTranscript {
        segments = segments == null ? List.of() : List.copyOf(segments);
        captionTrackName = captionTrackName == null ? "" : captionTrackName;
        availableCaptionTracks = availableCaptionTracks == null
                ? List.of()
                : List.copyOf(availableCaptionTracks);
    }

    public ExtractedTranscript(
            String content,
            List<TranscriptSegmentDto> segments,
            String languageCode,
            boolean autoGenerated) {
        this(content, segments, languageCode, autoGenerated, "", List.of());
    }
}
