package com.timesync.notes.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.timesync.notes.integration.youtube.*;
import com.timesync.notes.service.impl.*;
import com.timesync.notes.exception.*;
import org.junit.jupiter.api.*;
import org.springframework.http.MediaType;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.web.client.RestClient;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.*;
import static org.springframework.test.web.client.response.MockRestResponseCreators.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

class SubtitleRetrievalTest {
    private MockRestServiceServer server;
    private YoutubeExtractionServiceImpl service;
    private YoutubePlayerResponseClient player;
    private static final String BASE = "https://example.test/timedtext";
    private static final String VTT = "WEBVTT\n\n00:00:01.000 --> 00:00:04.000\nPRIVATE_TRANSCRIPT variables and functions explanation.\n";
    @BeforeEach void setup() {
        var builder = RestClient.builder();
        server = MockRestServiceServer.bindTo(builder).build();
        player = mock(YoutubePlayerResponseClient.class);
        service = new YoutubeExtractionServiceImpl(builder.build(), mock(YoutubeDataApiService.class), player,
            new ObjectMapper(), new YoutubeCaptionCircuitBreaker(60, 600));
        ReflectionTestUtils.setField(service, "timedTextBaseUrl", BASE);
    }
    @Test void malformedDiscoveryIsTemporaryRatherThanCaptionAbsence() {
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess("<html>Consent</html>", MediaType.TEXT_HTML));
        assertThrows(UpstreamServiceUnavailableException.class, () -> service.extractTranscript("abcdefghijk", "Original"));
        server.verify();
    }

    @Test void manualEmptyThenAsrSucceedsWithoutRepeatingManualUrl() {
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess(
            "<transcript_list><track lang_code='en'/><track lang_code='en' kind='asr'/></transcript_list>", MediaType.TEXT_XML));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt")).andRespond(withSuccess("", MediaType.TEXT_PLAIN));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt&kind=asr")).andRespond(withSuccess(VTT, MediaType.TEXT_PLAIN));
        assertTrue(service.extractTranscript("abcdefghijk", "Original").autoGenerated());
        server.verify();
    }
    @Test void discoveredAsrEmptyThenLegacyManualSucceeds() {
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess(
            "<transcript_list><track lang_code='en' kind='asr'/></transcript_list>", MediaType.TEXT_XML));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt&kind=asr")).andRespond(withSuccess("", MediaType.TEXT_PLAIN));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt")).andRespond(withSuccess(VTT, MediaType.TEXT_PLAIN));
        assertFalse(service.extractTranscript("abcdefghijk", "Original").autoGenerated());
        server.verify();
    }
    @Test void identicalDiscoveryAndFallbackUrlIsNotRequestedTwice() {
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess(
            "<transcript_list><track lang_code='en'/></transcript_list>", MediaType.TEXT_XML));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt")).andRespond(withSuccess("", MediaType.TEXT_PLAIN));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt&kind=asr")).andRespond(withSuccess("", MediaType.TEXT_PLAIN));
        assertEquals("CAPTIONS_UNAVAILABLE", assertThrows(UnprocessableVideoException.class,
            () -> service.extractTranscript("abcdefghijk", "Original")).getErrorCode());
        server.verify();
    }
    @Test void trackNameEncodesLiteralPlusAmpersandAndUnicodeExactlyOnce() {
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess(
            "<transcript_list><track lang_code='en' name='English + CC &amp; हिन्दी'/></transcript_list>", MediaType.TEXT_XML));
        server.expect(requestTo(BASE + "?v=abcdefghijk&lang=en&fmt=vtt&name=English%20%2B%20CC%20%26%20%E0%A4%B9%E0%A4%BF%E0%A4%A8%E0%A5%8D%E0%A4%A6%E0%A5%80"))
            .andRespond(withSuccess(VTT, MediaType.TEXT_PLAIN));
        assertFalse(service.extractTranscript("abcdefghijk", "Original").segments().isEmpty());
        server.verify();
    }

    @Test void signedQueryRemainsEncodedAndLogsContainOnlyMetadata() throws Exception {
        String url = BASE + "?lang=en&name=English%20CC&kind=asr&tlang=hi&sig=PRIVATE_SIGNED%2Btoken&fmt=srv3";
        when(player.getPlayerResponseJson("abcdefghijk", YoutubeContentOperation.WATCH_PAGE)).thenReturn(
            "{\"captions\":{\"playerCaptionsTracklistRenderer\":{\"captionTracks\":[{\"baseUrl\":\"" + url + "\",\"languageCode\":\"en\",\"kind\":\"asr\"}]}}}");
        server.expect(requestTo(BASE + "?type=list&v=abcdefghijk")).andRespond(withSuccess("", MediaType.TEXT_XML));
        server.expect(requestTo(url.replace("fmt=srv3", "fmt=vtt"))).andRespond(withSuccess(VTT, MediaType.TEXT_HTML));
        var logger = (ch.qos.logback.classic.Logger) org.slf4j.LoggerFactory.getLogger(YoutubeExtractionServiceImpl.class);
        var previous = logger.getLevel();
        var logs = new ch.qos.logback.core.read.ListAppender<ch.qos.logback.classic.spi.ILoggingEvent>();
        logs.start(); logger.addAppender(logs); logger.setLevel(ch.qos.logback.classic.Level.DEBUG);
        try {
            assertFalse(service.extractTranscript("abcdefghijk", "Original").segments().isEmpty());
            String output = String.join("\n", logs.list.stream().map(e -> e.getFormattedMessage()).toList());
            assertTrue(output.contains("reason=OK")); assertTrue(output.contains("payloadBytes="));
            assertFalse(output.contains("PRIVATE_TRANSCRIPT")); assertFalse(output.contains("PRIVATE_SIGNED"));
            assertFalse(output.contains(BASE));
        } finally { logger.detachAppender(logs); logger.setLevel(previous); logs.stop(); }
        server.verify();
    }
}
