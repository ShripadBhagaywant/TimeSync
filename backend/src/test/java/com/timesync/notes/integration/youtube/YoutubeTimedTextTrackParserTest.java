package com.timesync.notes.integration.youtube;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class YoutubeTimedTextTrackParserTest {

    @Test
    void parsesManualAndAutomaticCaptionOptions() {
        var tracks = YoutubeTimedTextTrackParser.parse("""
                <?xml version="1.0" encoding="utf-8" ?>
                <transcript_list>
                  <track id="0" name="English" lang_code="en" lang_translated="English" />
                  <track id="1" name="" lang_code="hi" lang_translated="Hindi" kind="asr" />
                </transcript_list>
                """);

        assertEquals(2, tracks.size());
        assertEquals("en", tracks.get(0).languageCode());
        assertTrue(tracks.get(1).autoGenerated());
    }

    @Test
    void rejectsXmlWithDoctypeDeclarations() {
        assertTrue(YoutubeTimedTextTrackParser.parse("""
                <!DOCTYPE foo [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>
                <transcript_list><track lang_code="en" name="&xxe;" /></transcript_list>
                """).isEmpty());
    }
}
